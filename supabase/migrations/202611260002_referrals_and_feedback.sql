-- Referral tracking and Help & Feedback persistence.
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS referral_code text,
  ADD COLUMN IF NOT EXISTS referred_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL;

CREATE UNIQUE INDEX IF NOT EXISTS profiles_referral_code_unique
  ON public.profiles (referral_code)
  WHERE referral_code IS NOT NULL;

CREATE INDEX IF NOT EXISTS profiles_referred_by_idx
  ON public.profiles (referred_by)
  WHERE referred_by IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.referral_clicks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  visitor_id text NOT NULL,
  clicked_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (referrer_id, visitor_id)
);

ALTER TABLE public.referral_clicks ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS referral_clicks_referrer_clicked_idx
  ON public.referral_clicks (referrer_id, clicked_at DESC);

CREATE OR REPLACE FUNCTION public.ensure_referral_code()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_code text;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  SELECT referral_code INTO v_code
  FROM public.profiles
  WHERE id = v_user_id;

  IF v_code IS NOT NULL THEN
    RETURN v_code;
  END IF;

  LOOP
    v_code := upper(substr(md5(random()::text || clock_timestamp()::text || v_user_id::text), 1, 10));
    EXIT WHEN NOT EXISTS (
      SELECT 1 FROM public.profiles WHERE referral_code = v_code
    );
  END LOOP;

  UPDATE public.profiles
  SET referral_code = v_code
  WHERE id = v_user_id AND referral_code IS NULL;

  SELECT referral_code INTO v_code
  FROM public.profiles
  WHERE id = v_user_id;

  RETURN v_code;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_referral_click(p_code text, p_visitor_id text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_referrer_id uuid;
  v_inserted integer := 0;
BEGIN
  IF p_code IS NULL OR length(trim(p_code)) < 4 OR length(trim(p_code)) > 32
     OR p_visitor_id IS NULL OR length(trim(p_visitor_id)) < 16 OR length(trim(p_visitor_id)) > 80 THEN
    RETURN false;
  END IF;

  SELECT id INTO v_referrer_id
  FROM public.profiles
  WHERE referral_code = upper(trim(p_code));

  IF v_referrer_id IS NULL OR v_referrer_id = auth.uid() THEN
    RETURN false;
  END IF;

  INSERT INTO public.referral_clicks (referrer_id, visitor_id)
  VALUES (v_referrer_id, trim(p_visitor_id))
  ON CONFLICT (referrer_id, visitor_id) DO NOTHING;

  GET DIAGNOSTICS v_inserted = ROW_COUNT;
  RETURN v_inserted > 0;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_referral_stats()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_invited bigint;
  v_joined bigint;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  SELECT count(*) INTO v_invited
  FROM public.referral_clicks
  WHERE referrer_id = v_user_id;

  SELECT count(*) INTO v_joined
  FROM public.profiles
  WHERE referred_by = v_user_id;

  RETURN jsonb_build_object(
    'invited_count', coalesce(v_invited, 0),
    'joined_count', coalesce(v_joined, 0)
  );
END;
$$;

CREATE TABLE IF NOT EXISTS public.feedback_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL,
  type text NOT NULL CHECK (type IN ('Feedback', 'Help', 'Bug')),
  message text NOT NULL CHECK (length(trim(message)) BETWEEN 1 AND 5000),
  app_version text,
  device_model text,
  user_agent text,
  status text NOT NULL DEFAULT 'new',
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.feedback_submissions ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS feedback_submissions_user_created_idx
  ON public.feedback_submissions (user_id, created_at DESC);

CREATE POLICY "Users can read their own feedback submissions"
  ON public.feedback_submissions FOR SELECT TO authenticated
  USING (user_id = auth.uid());

CREATE POLICY "Users can create their own feedback submissions"
  ON public.feedback_submissions FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid());

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  display_name_text text;
  city_text text;
  referral_input text;
  referrer_id uuid;
  referral_code_text text;
BEGIN
  display_name_text := coalesce(
    nullif(new.raw_user_meta_data->>'display_name', ''),
    nullif(new.raw_user_meta_data->>'full_name', ''),
    nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
    'Protlys member'
  );
  city_text := nullif(new.raw_user_meta_data->>'city', '');
  referral_input := upper(trim(coalesce(new.raw_user_meta_data->>'referral_code', '')));

  IF referral_input <> '' THEN
    SELECT id INTO referrer_id
    FROM public.profiles
    WHERE referral_code = referral_input AND id <> new.id
    LIMIT 1;
  END IF;

  LOOP
    referral_code_text := upper(substr(md5(random()::text || clock_timestamp()::text || new.id::text), 1, 10));
    EXIT WHEN NOT EXISTS (
      SELECT 1 FROM public.profiles WHERE referral_code = referral_code_text
    );
  END LOOP;

  INSERT INTO public.profiles (id, display_name, city, referral_code, referred_by)
  VALUES (new.id, display_name_text, city_text, referral_code_text, referrer_id)
  ON CONFLICT (id) DO UPDATE
    SET display_name = excluded.display_name,
        city = coalesce(public.profiles.city, excluded.city),
        referral_code = coalesce(public.profiles.referral_code, excluded.referral_code),
        referred_by = coalesce(public.profiles.referred_by, excluded.referred_by);

  INSERT INTO public.profile_private (user_id, email)
  VALUES (new.id, new.email)
  ON CONFLICT (user_id) DO UPDATE SET email = excluded.email;

  RETURN new;
END;
$function$;

