create table if not exists public.referral_codes (
  user_id uuid primary key references auth.users(id) on delete cascade,
  code text not null unique check (code ~ '^[A-Z0-9]{8,16}$'),
  created_at timestamptz not null default now()
);

create table if not exists public.referral_visits (
  id bigint generated by default as identity primary key,
  referrer_id uuid not null references auth.users(id) on delete cascade,
  code text not null,
  visitor_key text not null check (char_length(visitor_key) between 8 and 100),
  visited_at timestamptz not null default now(),
  unique (code, visitor_key)
);

create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  referrer_id uuid not null references auth.users(id) on delete cascade,
  referred_user_id uuid not null unique references auth.users(id) on delete cascade,
  referral_code text not null,
  created_at timestamptz not null default now(),
  constraint referrals_no_self check (referrer_id <> referred_user_id)
);

create index if not exists referral_visits_referrer_idx on public.referral_visits(referrer_id, visited_at desc);
create index if not exists referrals_referrer_idx on public.referrals(referrer_id, created_at desc);

alter table public.referral_codes enable row level security;
alter table public.referral_visits enable row level security;
alter table public.referrals enable row level security;

drop policy if exists "Users can read own referral code" on public.referral_codes;
create policy "Users can read own referral code" on public.referral_codes
  for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "Users can read own referral relationships" on public.referrals;
create policy "Users can read own referral relationships" on public.referrals
  for select to authenticated using (referrer_id = (select auth.uid()) or referred_user_id = (select auth.uid()));

create or replace function public.ensure_my_referral_code()
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_code text;
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  select rc.code into v_code from public.referral_codes rc where rc.user_id = v_user;
  if v_code is not null then return v_code; end if;
  loop
    v_code := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));
    insert into public.referral_codes(user_id, code) values (v_user, v_code)
      on conflict do nothing;
    select rc.code into v_code from public.referral_codes rc where rc.user_id = v_user;
    exit when v_code is not null;
  end loop;
  return v_code;
end;
$$;

create or replace function public.record_referral_visit(p_code text, p_visitor_key text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_referrer uuid;
  v_code text := upper(trim(coalesce(p_code, '')));
  v_visitor text := trim(coalesce(p_visitor_key, ''));
begin
  if v_code !~ '^[A-Z0-9]{8,16}$' or char_length(v_visitor) < 8 or char_length(v_visitor) > 100 then
    return false;
  end if;
  select rc.user_id into v_referrer from public.referral_codes rc where rc.code = v_code;
  if v_referrer is null then return false; end if;
  insert into public.referral_visits(referrer_id, code, visitor_key)
    values (v_referrer, v_code, v_visitor)
    on conflict (code, visitor_key) do nothing;
  return true;
end;
$$;

create or replace function public.claim_referral_code(p_code text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_referrer uuid;
  v_code text := upper(trim(coalesce(p_code, '')));
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  if v_code !~ '^[A-Z0-9]{8,16}$' then return false; end if;
  select rc.user_id into v_referrer from public.referral_codes rc where rc.code = v_code;
  if v_referrer is null or v_referrer = v_user then return false; end if;
  insert into public.referrals(referrer_id, referred_user_id, referral_code)
    values (v_referrer, v_user, v_code)
    on conflict (referred_user_id) do nothing;
  return found;
end;
$$;

create or replace function public.get_my_referral_stats()
returns table(invited_count bigint, joined_count bigint)
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select count(*) from public.referral_visits rv where rv.referrer_id = auth.uid()),
    (select count(*) from public.referrals r where r.referrer_id = auth.uid());
$$;

create table if not exists public.support_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  email text,
  category text not null check (category in ('feedback', 'help', 'bug')),
  message text not null check (char_length(btrim(message)) between 5 and 4000),
  app_version text,
  device_info text,
  created_at timestamptz not null default now()
);

create index if not exists support_requests_user_created_idx on public.support_requests(user_id, created_at desc);
alter table public.support_requests enable row level security;

drop policy if exists "Users can read own support requests" on public.support_requests;
create policy "Users can read own support requests" on public.support_requests
  for select to authenticated using (user_id = (select auth.uid()));

create or replace function public.submit_support_request(
  p_category text,
  p_message text,
  p_app_version text default null,
  p_device_info text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_email text;
  v_id uuid;
  v_category text := lower(trim(coalesce(p_category, '')));
  v_message text := trim(coalesce(p_message, ''));
  v_recent integer;
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  if v_category not in ('feedback', 'help', 'bug') then raise exception 'Choose feedback, help or bug'; end if;
  if char_length(v_message) < 5 or char_length(v_message) > 4000 then raise exception 'Message must be between 5 and 4000 characters'; end if;
  select count(*) into v_recent from public.support_requests sr
    where sr.user_id = v_user and sr.created_at > now() - interval '10 minutes';
  if v_recent >= 3 then raise exception 'Please wait before sending another message'; end if;
  select u.email into v_email from auth.users u where u.id = v_user;
  insert into public.support_requests(user_id, email, category, message, app_version, device_info)
    values (v_user, v_email, v_category, v_message, left(p_app_version, 80), left(p_device_info, 500))
    returning id into v_id;
  return v_id;
end;
$$;

