create extension if not exists pgcrypto with schema extensions;
alter table public.groups add column if not exists invite_code_created_at timestamptz;
alter table public.groups add column if not exists invite_code_disabled boolean not null default false;
alter table public.groups add column if not exists member_limit integer check (member_limit is null or member_limit > 0);

create or replace function private.normalise_invite_code(p_code text) returns text language sql immutable set search_path='' as $$
 select upper(regexp_replace(coalesce(p_code,''),'[[:space:]-]+','','g'));
$$;

create or replace function public.generate_invite_code() returns text language plpgsql security definer set search_path='' as $$
declare
 v_alphabet constant text:='ABCDEFGHJKMNPQRSTUVWXYZ23456789'; v_bytes bytea; v_code text; v_i integer; v_try integer:=0;
begin
 loop
  v_try:=v_try+1; if v_try > 50 then raise exception 'Could not generate a unique invite code'; end if;
  v_bytes:=extensions.gen_random_bytes(8); v_code:='';
  for v_i in 0..7 loop v_code:=v_code||substr(v_alphabet,(get_byte(v_bytes,v_i)%length(v_alphabet))+1,1); end loop;
  exit when not exists(select 1 from public.groups g where upper(g.invite_code)=v_code);
 end loop;
 return v_code;
end $$;
revoke execute on function public.generate_invite_code() from public,anon,authenticated;

alter table public.groups alter column invite_code drop not null;
alter table public.groups alter column invite_code drop default;
update public.groups set invite_code=public.generate_invite_code(),invite_code_created_at=coalesce(invite_code_created_at,now()) where invite_code is null or btrim(invite_code)='';
update public.groups set invite_code_created_at=coalesce(invite_code_created_at,created_at,now());
alter table public.groups alter column invite_code set not null;
alter table public.groups drop constraint if exists groups_invite_code_key;
create unique index if not exists groups_invite_code_upper_key on public.groups(upper(invite_code));

create or replace function private.set_group_invite_code() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.invite_code is null or btrim(new.invite_code)='' then new.invite_code:=public.generate_invite_code(); end if;
 new.invite_code:=private.normalise_invite_code(new.invite_code);
 new.invite_code_created_at:=coalesce(new.invite_code_created_at,now());
 return new;
end $$;
drop trigger if exists groups_invite_code_trigger on public.groups;
create trigger groups_invite_code_trigger before insert on public.groups for each row execute function private.set_group_invite_code();

create table if not exists public.join_attempts(
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.profiles(id) on delete cascade,
 attempted_at timestamptz not null default now(),
 success boolean not null default false
);
create index if not exists join_attempts_user_failed_idx on public.join_attempts(user_id,attempted_at desc) where success=false;
alter table public.join_attempts enable row level security;
revoke all on table public.join_attempts from anon,authenticated;

drop function if exists public.join_group_by_invite_code(text);
create or replace function public.join_group_by_code(p_code text) returns jsonb language plpgsql security definer set search_path='' as $$
declare
 v_uid uuid:=(select auth.uid()); v_code text:=private.normalise_invite_code(p_code); v_group public.groups%rowtype;
 v_count integer; v_failed integer; v_oldest timestamptz; v_minutes integer;
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 select count(*),min(attempted_at) into v_failed,v_oldest from public.join_attempts where user_id=v_uid and success=false and attempted_at>now()-interval '1 hour';
 if v_failed >= 10 then
  v_minutes:=greatest(1,ceil(extract(epoch from((v_oldest+interval '1 hour')-now()))/60.0)::integer);
  return jsonb_build_object('status','rate_limited','minutes',v_minutes);
 end if;
 if length(v_code)<>8 or v_code!~'^[ABCDEFGHJKMNPQRSTUVWXYZ23456789]{8}$' then
  insert into public.join_attempts(user_id,success) values(v_uid,false); return jsonb_build_object('status','not_found');
 end if;
 select * into v_group from public.groups where upper(invite_code)=v_code limit 1;
 if v_group.id is null then insert into public.join_attempts(user_id,success) values(v_uid,false); return jsonb_build_object('status','not_found'); end if;
 if exists(select 1 from public.group_members where group_id=v_group.id and user_id=v_uid) then
  select count(*) into v_count from public.group_members where group_id=v_group.id;
  insert into public.join_attempts(user_id,success) values(v_uid,true);
  return jsonb_build_object('status','already_member','group_id',v_group.id,'name',v_group.name,'member_count',v_count);
 end if;
 if v_group.invite_code_disabled then insert into public.join_attempts(user_id,success) values(v_uid,false); return jsonb_build_object('status','code_disabled'); end if;
 select count(*) into v_count from public.group_members where group_id=v_group.id;
 if v_group.member_limit is not null and v_count>=v_group.member_limit then
  insert into public.join_attempts(user_id,success) values(v_uid,false); return jsonb_build_object('status','group_full');
 end if;
 insert into public.group_members(group_id,user_id,role) values(v_group.id,v_uid,'member'::public.group_role) on conflict(group_id,user_id) do nothing;
 select count(*) into v_count from public.group_members where group_id=v_group.id;
 insert into public.join_attempts(user_id,success) values(v_uid,true);
 return jsonb_build_object('status','joined','group_id',v_group.id,'name',v_group.name,'member_count',v_count);
end $$;
revoke execute on function public.join_group_by_code(text) from public,anon;
grant execute on function public.join_group_by_code(text) to authenticated;

create or replace function public.regenerate_invite_code(p_group_id uuid) returns jsonb language plpgsql security definer set search_path='' as $$
declare v_uid uuid:=(select auth.uid()); v_group public.groups%rowtype; v_code text;
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if not exists(select 1 from public.group_members gm where gm.group_id=p_group_id and gm.user_id=v_uid and gm.role='admin'::public.group_role)
 and not exists(select 1 from public.groups g where g.id=p_group_id and g.created_by=v_uid)
 then raise exception 'Only group admins can reset invite codes'; end if;
 v_code:=public.generate_invite_code();
 update public.groups set invite_code=v_code,invite_code_created_at=now(),invite_code_disabled=false where id=p_group_id returning * into v_group;
 if v_group.id is null then raise exception 'Group not found'; end if;
 return jsonb_build_object('status','reset','group_id',v_group.id,'name',v_group.name,'invite_code',v_group.invite_code);
end $$;
revoke execute on function public.regenerate_invite_code(uuid) from public,anon;
grant execute on function public.regenerate_invite_code(uuid) to authenticated;

